const EmojiPicker = (function () {

    let loaded = false;
    let $modal, $grid;
    let activeInput = null;
    const namespaces = new Set();
    const STORAGE_KEY = 'emoji_recent_v1';

    /* ---------- GLOBAL LOAD ---------- */

    function globalLoad(opts) {
        if (loaded) return;

        $modal = $(opts.emojiModalSelector);
        $grid = $modal.find('#emojiPickerGrid');

        restoreRecent();
        bindTabs();
        bindEmojiClick();

        loaded = true;
    }

    /* ---------- CREATE (DYNAMIC TRIGGERS + INPUTS) ---------- */

    function create(opts) {
        if (!loaded) {
            console.error('EmojiPicker.globalLoad must be called first');
            return;
        }

        const ns = opts.namespace?.toLowerCase();
        if (!ns || namespaces.has(ns)) {
            console.error(`Invalid or duplicate namespace "${ns}"`);
            return;
        }
        namespaces.add(ns);

        // 🔥 DELEGATED — trigger & input BOTH dynamic
        $(document).on('click', opts.triggerSelector, function () {

            const $input = $(this)
                .closest(opts.inputContainerSelector)
                .find(opts.inputSelector);

            if (!$input.length) return;

            activeInput = $input;

            activateTab('recent');
            render('recent');
            $modal.modal('show');
        });
    }

    /* ---------- MODAL STACK HANDLER ---------- */

    function showEmojiModal($modal) {
        const hasOtherOpenModal =
            $('.modal.show').not($modal).length > 0;

        if (hasOtherOpenModal) {
            // 🔥 Inside another modal
            $modal.addClass('modal-stack');
            $modal.modal({
                backdrop: false,
                keyboard: false
            });
        } else {
            // 🔥 Normal page
            $modal.removeClass('modal-stack');
            $modal.modal({
                backdrop: true,
                keyboard: true
            });
        }

        $modal.modal('show');
    }

    /* ---------- RENDER ---------- */

    function render(category) {
        if (category === 'delete') {
            backspace();
            return;
        }

        const emojis = window.EMOJI_DATA[category] || [];
        $grid.empty();

        emojis.forEach(e => {
            const $btn = $('<button/>', { type: 'button', class: 'emoji-btn' });
            $('<span/>', { class: 'emoji-char', text: e }).appendTo($btn);
            $grid.append($btn);
        });

        $grid.scrollTop(0);
    }

    /* ---------- EVENTS ---------- */

    function bindTabs() {
        $modal.on('click', '.emoji-tabs .nav-link', function () {
            const cat = $(this).data('category');
            activateTab(cat);
            render(cat);
        });
    }

    function bindEmojiClick() {
        $grid.on('click', '.emoji-btn', function () {
            if (!activeInput) return;

            const emoji = $(this).text();
            insertAtCursor(activeInput[0], emoji);
            saveRecent(emoji);

            activeInput.focus();
        });
    }

    function activateTab(cat) {
        $('.emoji-tabs .nav-link').removeClass('active');
        $(`.emoji-tabs .nav-link[data-category="${cat}"]`).addClass('active');
    }

    /* ---------- INPUT HELPERS ---------- */

    function insertAtCursor(input, text) {
        const start = input.selectionStart ?? input.value.length;
        const end = input.selectionEnd ?? input.value.length;

        input.value =
            input.value.slice(0, start) +
            text +
            input.value.slice(end);

        input.selectionStart = input.selectionEnd = start + text.length;
        input.dispatchEvent(new Event('input', { bubbles: true }));
    }

    function backspace() {
        if (!activeInput) return;

        const input = activeInput[0];
        input.value = Array.from(input.value).slice(0, -1).join('');
        input.dispatchEvent(new Event('input', { bubbles: true }));
        input.focus();
    }

    /* ---------- RECENT ---------- */

    function saveRecent(emoji) {
        let recent = window.EMOJI_DATA.recent.filter(e => e !== emoji);
        recent.unshift(emoji);
        if (recent.length > 24) recent.pop();

        window.EMOJI_DATA.recent = recent;
        localStorage.setItem(STORAGE_KEY, JSON.stringify(recent));
    }

    function restoreRecent() {
        const saved = localStorage.getItem(STORAGE_KEY);
        if (saved) {
            window.EMOJI_DATA.recent = JSON.parse(saved);
        }
    }

    return {
        globalLoad,
        create
    };

})();
